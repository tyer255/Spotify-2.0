// Global in-memory cache shared across React components during runtime
const runtimeArtistImageCache = new Map<string, string>();
const activeFetchPromises = new Map<string, Promise<string>>();

export function getArtistPortrait(nameOrId?: string): string {
  if (!nameOrId || typeof nameOrId !== 'string') return '';
  const clean = nameOrId.toLowerCase().trim().replace(/^artist-/, '');
  const slug = clean.replace(/[^a-z0-9]+/g, ' ').trim();

  // 1. Runtime cache check
  if (runtimeArtistImageCache.has(clean)) return runtimeArtistImageCache.get(clean)!;
  if (runtimeArtistImageCache.has(slug)) return runtimeArtistImageCache.get(slug)!;

  // 2. Direct catalog check
  if (ARTIST_PORTRAIT_CATALOG[clean]) return ARTIST_PORTRAIT_CATALOG[clean];
  if (ARTIST_PORTRAIT_CATALOG[slug]) return ARTIST_PORTRAIT_CATALOG[slug];

  // 3. Exact slug match in catalog keys
  for (const [key, url] of Object.entries(ARTIST_PORTRAIT_CATALOG)) {
    if (key === slug || (slug.length > 4 && (slug.startsWith(key) || key.startsWith(slug)))) {
      return url;
    }
  }

  return '';
}

export function cacheArtistPortrait(nameOrId: string, url: string): void {
  if (!nameOrId || !url || !url.startsWith('http')) return;
  const clean = nameOrId.toLowerCase().trim().replace(/^artist-/, '');
  const slug = clean.replace(/[^a-z0-9]+/g, ' ').trim();
  runtimeArtistImageCache.set(clean, url);
  runtimeArtistImageCache.set(slug, url);
}

/**
 * Dynamically fetches live HD artist portrait from server (/api/artist-image)
 * and saves into cache for seamless real-time rendering.
 */
export async function fetchArtistPortraitLive(nameOrId: string): Promise<string> {
  if (!nameOrId || typeof nameOrId !== 'string') return '';
  const clean = nameOrId.toLowerCase().trim().replace(/^artist-/, '');
  const slug = clean.replace(/[^a-z0-9]+/g, ' ').trim();

  const cached = getArtistPortrait(slug);
  if (cached) return cached;

  if (activeFetchPromises.has(slug)) {
    return activeFetchPromises.get(slug)!;
  }

  const p = (async () => {
    try {
      const res = await fetch(`/api/artist-image?name=${encodeURIComponent(nameOrId)}`);
      if (res.ok) {
        const data = await res.json();
        if (data && data.imageUrl && data.imageUrl.startsWith('http')) {
          cacheArtistPortrait(clean, data.imageUrl);
          cacheArtistPortrait(slug, data.imageUrl);
          return data.imageUrl;
        }
      }
    } catch {
      // ignore
    } finally {
      activeFetchPromises.delete(slug);
    }
    return '';
  })();

  activeFetchPromises.set(slug, p);
  return p;
}
